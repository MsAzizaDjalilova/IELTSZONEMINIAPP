export function detectLang(code) {
  const c = String(code || '').toLowerCase();
  if (c.startsWith('ru')) return 'ru';
  if (c.startsWith('en')) return 'en';
  return 'uz';
}

export function makeT(lang) {
  const d = dict[lang] || dict.uz;
  const t = (key, ...args) => {
    const v = d[key] ?? dict.uz[key] ?? key;
    return typeof v === 'function' ? v(...args) : v;
  };
  t.lang = lang;
  t.L = (obj) => (obj && typeof obj === 'object' ? obj[lang] || obj.uz || '' : obj || '');
  t.price = (n) => (n ? `${Number(n).toLocaleString('ru-RU').replace(/ /g, ' ')}` : null);
  t.date = (d) => {
    if (!d) return '';
    const locale = lang === 'ru' ? 'ru-RU' : lang === 'en' ? 'en-GB' : 'uz-UZ';
    try {
      return new Date(d).toLocaleDateString(locale, { day: 'numeric', month: 'long' });
    } catch {
      return new Date(d).toISOString().slice(0, 10);
    }
  };
  return t;
}
